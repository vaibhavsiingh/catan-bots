"""Round robin between agents through the harness, and ratings on one scale (Bradley-Terry, Elo units).

usage:
  python tools/roundrobin.py OUT NAME=agent.py[@KEY=VAL,KEY=VAL] NAME=... [--games 300] [--seed0 700000]
      [--par 8] [--chunk 20] [--noclock] [--anchor F] [--rate-only]

- Every pair plays --games games: game i on board seed0 + i//2, seats alternating, the same dice from both
  seats (tools/ab.py's worker, harness.match.play_chunk). All pairs use the same boards.
- KEY=VAL pairs are environment variables of THAT agent only: each agent runs through a generated wrapper
  (OUT/agents/NAME/agent.py) that sets them inside its own process. So CAT=AB for one agent and CAT=F for
  another do not collide.
- Workers run at the lowest CPU priority (nice 19); --par caps how many run at once.
- Finished chunks stay in OUT/pairs/A__B/, so adding an agent later plays only its new pairs.
- Ratings: Bradley-Terry fitted by minorization-maximization on decisive games, with half a win added each
  way per pair so that a perfect score stays finite; 400 * log10 scale, the anchor at 1500. The 95% intervals
  come from 200 parametric bootstrap resamples of every pair's result. Written to OUT/ratings.md.
"""

import argparse
import json
import math
import os
import random
import re
import subprocess
import sys
import time
from itertools import combinations

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AB = os.path.join(ROOT, "tools", "ab.py")

WRAPPER = '''"""Generated by tools/roundrobin.py: {path} with {env}."""
import os
import runpy
import sys

os.environ.update({env!r})
PATH = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), {rel!r}))
sys.path.insert(0, os.path.dirname(PATH))
Agent = runpy.run_path(PATH)["Agent"]
'''


def parse(spec):
    name, rest = spec.split("=", 1)
    path, _, kv = rest.partition("@")
    env = dict(p.split("=", 1) for p in re.split(r",(?=[A-Za-z_][A-Za-z0-9_]*=)", kv)) if kv else {}  # values may hold commas
    return name, os.path.abspath(path), env


def wrapper(out, name, path, env):
    d = os.path.join(out, "agents", name)
    os.makedirs(d, exist_ok=True)
    f = os.path.join(d, "agent.py")
    text = WRAPPER.format(path=os.path.relpath(path, ROOT), env=env, rel=os.path.relpath(path, d))
    if not os.path.exists(f) or open(f).read() != text:
        with open(f, "w") as fh:
            fh.write(text)
    return f


def results(out, names):
    """wins[a][b] = decisive games a won against b"""
    wins = {a: {b: 0 for b in names} for a in names}
    for a, b in combinations(names, 2):
        d = os.path.join(out, "pairs", f"{a}__{b}")
        if not os.path.isdir(d):
            a, b = b, a  # folders are named in the order the agents were first listed
            d = os.path.join(out, "pairs", f"{a}__{b}")
        if not os.path.isdir(d):
            continue
        for f in os.listdir(d):
            if f.endswith(".json") and f != "pair.json":
                for r in json.load(open(os.path.join(d, f))):
                    if r["winner"] == "a":
                        wins[a][b] += 1
                    elif r["winner"] == "b":
                        wins[b][a] += 1
    return wins


def bradley_terry(wins, names, prior=0.5, iters=2000):
    w = {a: {b: wins[a][b] + (prior if a != b else 0) for b in names} for a in names}
    p = {a: 1.0 for a in names}
    for _ in range(iters):
        new = {}
        for a in names:
            den = sum((w[a][b] + w[b][a]) / (p[a] + p[b]) for b in names if b != a)
            new[a] = sum(w[a][b] for b in names if b != a) / den
        g = math.exp(sum(math.log(v) for v in new.values()) / len(new))
        p = {a: v / g for a, v in new.items()}
    return p


def ratings(out, names, anchor):
    """(wins, names that played, anchor or None, point ratings, sorted bootstrap ratings per agent)"""
    wins = results(out, names)
    played = {a for a in names if any(wins[a][b] + wins[b][a] for b in names)}
    names = [a for a in names if a in played]
    if len(names) < 2:
        return wins, names, None, {}, {}
    anchor = anchor if anchor in names else None

    def elo(wn):
        p = bradley_terry(wn, names)
        base = math.log10(p[anchor]) if anchor else sum(math.log10(v) for v in p.values()) / len(p)
        return {a: 1500 + 400 * (math.log10(v) - base) for a, v in p.items()}

    point = elo(wins)
    rng = random.Random(0)
    boot = {a: [] for a in names}
    for _ in range(200):
        wb = {a: {b: 0 for b in names} for a in names}
        for a, b in combinations(names, 2):
            n = wins[a][b] + wins[b][a]
            if n:
                k = sum(rng.random() < wins[a][b] / n for _ in range(n))
                wb[a][b], wb[b][a] = k, n - k
        for a, v in elo(wb).items():
            boot[a].append(v)
    return wins, names, anchor, point, {a: sorted(v) for a, v in boot.items()}


def rate(out, names, anchor):
    wins, names, anchor, point, boot = ratings(out, names, anchor)
    if len(names) < 2:
        return "no games yet"
    lines = [f"Ratings (Bradley-Terry, Elo scale, {anchor or 'mean'} = 1500; 95% bootstrap interval)", "",
             "| agent | rating | 95% interval | games |", "|---|---|---|---|"]
    for a in sorted(names, key=lambda x: -point[x]):
        lo, hi = boot[a][4], boot[a][194]
        g = sum(wins[a][b] + wins[b][a] for b in names)
        lines.append(f"| {a} | {point[a]:.0f} | {lo:.0f} – {hi:.0f} | {g} |")
    order = sorted(names, key=lambda x: -point[x])
    lines += ["", "Win rate of the row agent against the column agent (decisive games):", "",
              "| | " + " | ".join(order) + " |", "|---" * (len(order) + 1) + "|"]
    for a in order:
        cells = []
        for b in order:
            n = wins[a][b] + wins[b][a]
            cells.append("—" if a == b else (f"{100 * wins[a][b] / n:.0f}%" if n else ""))
        lines.append(f"| {a} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("agents", nargs="+")
    ap.add_argument("--games", type=int, default=300)
    ap.add_argument("--seed0", type=int, default=700000)
    ap.add_argument("--par", type=int, default=8)
    ap.add_argument("--chunk", type=int, default=20)
    ap.add_argument("--noclock", action="store_true")
    ap.add_argument("--anchor", default="F")
    ap.add_argument("--rate-only", action="store_true")
    a = ap.parse_args()
    assert a.chunk % 2 == 0, "chunks must hold whole boards (both seats)"
    out = os.path.abspath(a.out)
    agents = [parse(s) for s in a.agents]
    names = [n for n, _, _ in agents]
    assert len(set(names)) == len(names), "agent names must be unique"
    jobs = []
    if not a.rate_only:
        wrap = {n: wrapper(out, n, p, e) for n, p, e in agents}
        spec = {n: dict(path=os.path.relpath(p, ROOT), env=e) for n, p, e in agents}
        for x, y in combinations(names, 2):
            d = os.path.join(out, "pairs", f"{x}__{y}")
            os.makedirs(d, exist_ok=True)
            meta = dict(a=spec[x], b=spec[y], clock=not a.noclock, seed0=a.seed0)
            mf = os.path.join(d, "pair.json")
            if os.path.exists(mf):
                assert json.load(open(mf)) == meta, f"{x}__{y} already ran with other settings: {mf}"
            json.dump(meta, open(mf, "w"), indent=1)
            for lo in range(0, a.games, a.chunk):
                hi = min(lo + a.chunk, a.games)
                f = os.path.join(d, f"{a.seed0}_{lo}_{hi}.json")
                if not os.path.exists(f):
                    jobs.append((lo, x, y, hi, f))
        jobs.sort(key=lambda j: j[0])  # pairs interleaved: partial ratings stay balanced
    print(f"{len(jobs)} chunks to play, {a.par} at a time, nice 19", flush=True)
    running, done, t0 = [], 0, time.time()
    while jobs or running:
        while jobs and len(running) < a.par:
            lo, x, y, hi, f = jobs.pop(0)
            cmd = ["nice", "-n", "19", sys.executable, AB, "--worker", wrap[x], wrap[y], str(a.seed0), str(lo), str(hi),
                   f, str(int(not a.noclock)), ""]
            running.append((subprocess.Popen(cmd, cwd=ROOT, env=dict(os.environ, PYTHONHASHSEED="0", **({} if not a.noclock or "CATAN_CALL_TIMEOUT_S" in os.environ else {"CATAN_CALL_TIMEOUT_S": "120"}))), f"{x}__{y}", lo))
        time.sleep(2)
        for p in [r for r in running if r[0].poll() is not None]:
            running.remove(p)
            done += 1
            if p[0].returncode:
                print(f"chunk {p[1]} @{p[2]} failed (exit {p[0].returncode})", flush=True)
            if done % 10 == 0:
                print(f"[{time.strftime('%H:%M')}] {done} chunks done, {time.time() - t0:.0f}s", flush=True)
    table = rate(out, names, a.anchor)
    with open(os.path.join(out, "ratings.md"), "w") as fh:
        fh.write(table + "\n")
    print(table)


if __name__ == "__main__":
    main()
